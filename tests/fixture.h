static inline void lnc_test_place_candidate(
    uint8_t *text,
    size_t text_size,
    size_t offset)
{
    assert(text != NULL);
    assert(offset <= text_size);
    assert(LNC_NEEDS_CONFIRM_SIZE <= text_size - offset);

    memset(text + offset, 0xA5, LNC_NEEDS_CONFIRM_SIZE);
    memcpy(text + offset, lnc_test_entry, sizeof(lnc_test_entry));
    memcpy(text + offset + LNC_TEST_CORE_OFFSET,
        lnc_test_core, sizeof(lnc_test_core));
    memcpy(text + offset + LNC_TEST_DECISION_OFFSET,
        lnc_test_decision, sizeof(lnc_test_decision));
    memcpy(text + offset + LNC_TEST_SUFFIX_OFFSET,
        lnc_test_suffix, sizeof(lnc_test_suffix));
}

